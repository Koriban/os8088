#!/usr/bin/env python3
"""Generate BASIC/8088's tier B - one word per kernel slot (SPEC.md 150.57).

  python3 tools/os88basb.py            write apps/basic/bastierb.inc
  python3 tools/os88basb.py --check    exit 1 if it would change (the gate)

THE SOURCE IS apps/os88api.inc AND NOTHING ELSE, which is the whole point of
generating it: a slot renamed or re-registered there cannot leave a tier-B
word behind saying the old thing. §150.8 asked for exactly this.

WHAT IS EMITTED AND WHAT IS NOT. A slot qualifies when it is NUMBERED
(`KERNEL_SEG:0xNNNN`, which tier C's opcode can far-call) and its comment
names its input registers in the `AX = ...` form. A DOOR does not qualify -
`int OS88_RARE` and an index byte is a call tier C cannot make, and 150.57's
stub table is not built. Neither does a slot whose registers are written some
other way (`AL -> [gfx_color]`), because guessing one would put a program's
value in the wrong register, which assembles and runs.

ARGUMENTS ARE IN REGISTER ORDER - AX, BX, CX, DX, SI, DI - and the registers
a slot does not use are skipped. That is a uniform rule a programmer can
hold, and it is what lets the compiler emit tier C's positional form with
fillers: four of the 49 qualifying slots list their registers in another
order in the prose, and under this rule they need no special case.
"""
import os, re, sys

SRC = os.path.join("apps", "os88api.inc")
OUT = os.path.join("apps", "basic", "bastierb.inc")
ORD = {'AX': 0, 'AL': 0, 'AH': 0, 'BX': 1, 'BL': 1, 'BH': 1,
       'CX': 2, 'CL': 2, 'CH': 2, 'DX': 3, 'DL': 3, 'SI': 4, 'DI': 5}
RE_DEF = re.compile(r"%define\s+(OSAPI_\w+)\s+(\S+)(.*)")
RE_REG = re.compile(r"\b(AX|AL|AH|BX|BL|BH|CX|CL|CH|DX|DL|SI|DI)\s*=")


def slots():
    """(name, offset, [register positions, ascending]) for every qualifying slot."""
    out = []
    for line in open(SRC, encoding="utf-8", errors="replace"):
        m = RE_DEF.match(line)
        if not m:
            continue
        name, val, rest = m.group(1), m.group(2), m.group(3)
        hit = re.match(r"KERNEL_SEG:(0x[0-9A-Fa-f]+)$", val)
        if not hit:
            continue                       # a door, or not a call at all
        inputs = re.split(r"\bout\b", rest)[0]      # the OUT half is not ours
        pos = sorted({ORD[r] for r in RE_REG.findall(inputs)})
        if not pos:
            continue                       # takes nothing, or says so in prose
        out.append((name, int(hit.group(1), 16), pos))
    out.sort()
    return out


def build():
    rows = slots()
    w = ["; GENERATED by tools/os88basb.py - DO NOT EDIT. `--check` runs in"
         "\n; every `make`, so a hand edit here is a build failure, not a"
         "\n; surprise later (SPEC.md 150.57).",
         ";",
         "; One record per slot: a length-prefixed NAME, the kernel offset, the",
         "; count, and that many REGISTER POSITIONS (0=AX 1=BX 2=CX 3=DX 4=SI",
         "; 5=DI). A program writes its arguments in that order and the",
         "; compiler pads the registers between them.",
         "bas_tb:"]
    for name, off, pos in rows:
        w.append("    db %-2d, '%s'" % (len(name), name))
        w.append("    dw 0x%04X" % off)
        w.append("    db %d, %s" % (len(pos), ", ".join(str(p) for p in pos)))
    w.append("    db 0                            ; ...and the walk ends here")
    w.append("BAS_TB_N equ %d" % len(rows))
    return "\n".join(w) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        try:
            cur = open(OUT, encoding="utf-8").read()
        except FileNotFoundError:
            cur = None
        if cur != text:
            print("os88basb: %s is stale - run tools/os88basb.py" % OUT)
            return 1
        print("os88basb: %s is current (%d slots)" % (OUT, text.count("\n    dw ")))
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("os88basb: wrote %s (%d slots)" % (OUT, text.count("\n    dw ")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
